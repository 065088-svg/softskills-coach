"""Verified scenario bank.

Every question has exactly four learner replies, one for each rating:
    3 = Best, 2 = Acceptable, 1 = Weak, 0 = Poor   (see config.RATING_MEANING)

Scoring in "Verified" mode comes ONLY from these hand-written ratings - the AI
model is never asked to decide whether an answer is right. Partner lines are
written so they make sense after ANY of the four replies in the previous turn.
"""


def opt(rating, text, feedback):
    return {"rating": rating, "text": text, "feedback": feedback}


def turn(skill, partner_line, options, tip, note=""):
    return {
        "skill": skill,
        "partner_line": partner_line,
        "note": note,
        "options": options,
        "tip": tip,
    }


